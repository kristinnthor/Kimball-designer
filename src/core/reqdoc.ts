import { APP_VERSION } from './version';
import {
  ADDITIVITY,
  DIMENSION_KINDS,
  FACT_TABLE_TYPES,
  INTERVIEW_STATUSES,
  PRIORITIES,
  SCD_TYPES,
  STAKEHOLDER_TYPES,
  displayName,
  optionLabel,
  priorityScore,
  processesUsing,
  type KimballProject,
} from './model';
import { bubbleToMermaid } from './bubble';
import { busMatrixToMarkdown } from './busMatrix';
import { countBySeverity, validateProject } from './validate';
import { mdCell } from './text';

const dash = (s: string) => (s.trim() ? mdCell(s) : '—');

/** A complete, shareable requirements document in GitHub-flavoured Markdown. */
export function requirementsToMarkdown(project: KimballProject, now: string = new Date().toISOString()): string {
  const { meta, stakeholders, requirements, processes, dimensions } = project;
  const title = displayName(meta, 'Untitled project');
  const stakeholderName = (id: string) => displayName(stakeholders.find((s) => s.id === id) ?? { name: id });
  const processName = (id: string) => displayName(processes.find((p) => p.id === id) ?? { name: id });
  const out: string[] = [];
  const h = (s: string) => out.push('', s, '');

  out.push(
    `# ${title} — dimensional requirements`,
    '',
    `> Generated by Kimball Designer ${APP_VERSION} on ${now.slice(0, 10)}. Source: project file \`${meta.id}\`.`,
  );

  // 1 Overview
  h('## 1. Overview');
  out.push(
    `| | |`,
    `|---|---|`,
    `| **Purpose** | ${dash(meta.purpose)} |`,
    `| **Sponsor** | ${dash(meta.sponsor)} |`,
    `| **In scope** | ${dash(meta.scopeIn)} |`,
    `| **Out of scope** | ${dash(meta.scopeOut)} |`,
  );
  if (meta.successCriteria.length) {
    out.push('', '**Success criteria**', '', ...meta.successCriteria.map((s) => `- ${s}`));
  }

  // 2 Stakeholders
  h('## 2. Stakeholders');
  if (stakeholders.length === 0) out.push('_No stakeholders recorded._');
  else {
    out.push('| Name | Role | Type | Interview | Notes |', '|---|---|---|---|---|');
    for (const s of stakeholders) {
      out.push(
        `| ${dash(s.name)} | ${dash([s.role, s.department].filter(Boolean).join(', '))} | ${optionLabel(STAKEHOLDER_TYPES, s.type)} | ${optionLabel(INTERVIEW_STATUSES, s.interviewStatus)} | ${dash(s.notes)} |`,
      );
    }
  }

  // 3 Requirements
  h('## 3. Business requirements');
  if (requirements.length === 0) out.push('_No requirements recorded._');
  else {
    out.push('| # | Requirement | Priority | KPIs | Raised by | Business processes |', '|---|---|---|---|---|---|');
    requirements.forEach((r, i) => {
      out.push(
        `| R${i + 1} | ${dash(r.statement)} | ${optionLabel(PRIORITIES, r.priority)} | ${dash(r.kpis.join(', '))} | ${dash(r.stakeholderIds.map(stakeholderName).join(', '))} | ${dash(r.processIds.map(processName).join(', '))} |`,
      );
    });
  }

  // 4 Business processes
  h('## 4. Business processes');
  if (processes.length === 0) out.push('_No business processes recorded._');
  else {
    out.push('| Business process | Fact table type | Grain | Dimensions | Facts | Value | Feasibility |', '|---|---|---|---|---|---|---|');
    for (const p of processes) {
      out.push(
        `| ${dash(displayName(p))} | ${dash(optionLabel(FACT_TABLE_TYPES, p.factTableType))} | ${dash(p.grain)} | ${p.dimensions.length} | ${p.facts.length} | ${p.businessValue ?? '—'} | ${p.feasibility ?? '—'} |`,
      );
    }
    processes.forEach((p, i) => {
      out.push('', `### 4.${i + 1} ${displayName(p)}`, '');
      if (p.description.trim()) out.push(p.description.trim(), '');
      out.push(
        `- **Grain:** ${p.grain.trim() ? `\`${p.grain.trim()}\`` : '_not declared_'}`,
        `- **Fact table type:** ${optionLabel(FACT_TABLE_TYPES, p.factTableType) || '_not set_'}`,
        `- **Owner:** ${p.owner.trim() || '—'}`,
        `- **Source systems:** ${p.sourceSystems.join(', ') || '—'}`,
      );
      const reqs = requirements.filter((r) => r.processIds.includes(p.id));
      if (reqs.length) out.push(`- **Answers requirements:** ${reqs.map((r) => `R${requirements.indexOf(r) + 1}`).join(', ')}`);
      out.push('', '**Dimensions**', '');
      if (p.dimensions.length === 0) out.push('_None yet._');
      for (const u of p.dimensions) {
        const d = dimensions.find((x) => x.id === u.dimensionId);
        out.push(`- ${d ? displayName(d) : u.dimensionId}${u.roles.length ? ` — roles: ${u.roles.join(', ')}` : ''}`);
      }
      out.push('', '**Facts**', '');
      if (p.facts.length === 0) out.push(p.factTableType === 'factless' ? '_Factless fact table._' : '_None yet._');
      else {
        out.push('| Fact | Additivity | Unit | Description |', '|---|---|---|---|');
        for (const f of p.facts) {
          out.push(`| ${dash(displayName(f))} | ${optionLabel(ADDITIVITY, f.additivity)} | ${dash(f.unit)} | ${dash(f.description)} |`);
        }
      }
      if (p.dimensions.length) out.push('', '**Bubble diagram**', '', '```mermaid', bubbleToMermaid(project, p).trimEnd(), '```');
    });
  }

  // 5 Dimensions
  h('## 5. Dimensions');
  if (dimensions.length === 0) out.push('_No dimensions recorded._');
  else {
    out.push('| Dimension | Kind | Used by | Conformed | Key attributes | Description |', '|---|---|---|---|---|---|');
    for (const d of dimensions) {
      const users = processesUsing(project, d.id);
      const attrs = d.attributes
        .map((a) => `${displayName(a)}${a.scdType != null ? ` (${optionLabel(SCD_TYPES, a.scdType)})` : ''}`)
        .join(', ');
      out.push(
        `| ${dash(displayName(d))} | ${optionLabel(DIMENSION_KINDS, d.kind)} | ${dash(users.map((p) => displayName(p)).join(', '))} | ${users.length >= 2 ? 'Yes' : 'No'} | ${dash(attrs)} | ${dash(d.description)} |`,
      );
    }
    const withHierarchies = dimensions.filter((d) => d.hierarchies.length);
    if (withHierarchies.length) {
      out.push('', '**Hierarchies**', '', ...withHierarchies.map((d) => `- ${displayName(d)}: ${d.hierarchies.join('; ')}`));
    }
  }

  // 6 Bus matrix
  h('## 6. Enterprise bus matrix');
  out.push(busMatrixToMarkdown(project).trimEnd());

  // 7 Prioritisation
  h('## 7. Prioritisation');
  const scored = processes.filter((p) => priorityScore(p) != null).sort((a, b) => priorityScore(b)! - priorityScore(a)!);
  if (scored.length === 0) out.push('_No processes scored yet._');
  else {
    out.push('| Rank | Business process | Business value | Feasibility | Score |', '|---|---|---|---|---|');
    scored.forEach((p, i) =>
      out.push(`| ${i + 1} | ${dash(displayName(p))} | ${p.businessValue} | ${p.feasibility} | ${priorityScore(p)} |`),
    );
    out.push('', 'Score = business value × feasibility (1–25). Start with the highest-scoring process.');
  }

  // 8 Assumptions & open questions
  h('## 8. Assumptions and open questions');
  out.push('**Assumptions**', '');
  out.push(...(project.assumptions.length ? project.assumptions.map((a) => `- ${a.text}`) : ['_None recorded._']));
  out.push('', '**Open questions**', '');
  out.push(
    ...(project.openQuestions.length
      ? project.openQuestions.map((q) => `- [${q.status === 'answered' ? 'x' : ' '}] ${q.text}${q.owner ? ` — _${q.owner}_` : ''}`)
      : ['_None recorded._']),
  );

  // 9 Validation
  h('## 9. Validation summary');
  const findings = validateProject(project);
  const counts = countBySeverity(findings);
  out.push(`${counts.error} error(s), ${counts.warning} warning(s), ${counts.info} note(s).`);
  if (findings.length) {
    out.push('', '| Severity | Rule | Finding |', '|---|---|---|');
    for (const f of findings) out.push(`| ${f.severity} | ${f.code} | ${mdCell(f.message)} |`);
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}
