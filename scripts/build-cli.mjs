// Bundles src/cli into a single dependency-free ESM file inside the skill.
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));

await build({
  entryPoints: ['src/cli/main.ts'],
  outfile: 'plugin/skills/kimball-designer/scripts/kimball.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  charset: 'utf8',
  legalComments: 'none',
  define: { __APP_VERSION__: JSON.stringify(version) },
  banner: {
    js: '#!/usr/bin/env node\n// Kimball Designer CLI ' + version + ' — generated by `npm run build:cli`; do not edit. Source: src/cli/',
  },
  logLevel: 'warning',
});
console.log('built plugin/skills/kimball-designer/scripts/kimball.mjs');
